create table if not exists core.item_policy (
  item_id text primary key,
  moq numeric,
  pack_size numeric,
  item_grade text,
  service_level numeric,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists core.forecast_setting (
  setting_id smallint primary key default 1 check (setting_id = 1),
  train_start date not null,
  train_end date not null,
  test_start date not null,
  test_end date not null,
  granularity text not null default 'DAY' check (granularity in ('DAY','WEEK','MONTH')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (train_start <= train_end and test_start <= test_end and train_end < test_start)
);

create or replace view core.v_train_demand as
select u.usage_id, upper(regexp_replace(u.item_id, '[\s\-_]', '', 'g')) as item_id, u.use_date, u.qty, u.warehouse, u.note
from raw.usage_history u
cross join (select train_start, train_end from core.forecast_setting where active order by setting_id limit 1) s
where u.use_date between s.train_start and s.train_end;

create or replace view core.v_test_actual as
select u.usage_id, upper(regexp_replace(u.item_id, '[\s\-_]', '', 'g')) as item_id, u.use_date, u.qty, u.warehouse, u.note
from raw.usage_history u
cross join (select test_start, test_end from core.forecast_setting where active order by setting_id limit 1) s
where u.use_date between s.test_start and s.test_end;

create or replace view core.v_usage_effective as
with calc as (
  select item_id, count(*) as valid_days, round(avg(qty), 2) as daily_usage_avg, round(stddev_samp(qty), 2) as daily_usage_sd
  from core.v_train_demand
  where qty >= 0 and coalesce(note, '') not ilike '%프로젝트%'
  group by item_id
)
select c.item_id, coalesce(p.valid_days::bigint, c.valid_days) as valid_days,
  coalesce(p.daily_usage_avg, c.daily_usage_avg) as daily_usage_avg,
  coalesce(p.daily_usage_sd, c.daily_usage_sd) as daily_usage_sd,
  round(coalesce(p.daily_usage_avg, c.daily_usage_avg), 2) as usage_used,
  round(coalesce(p.daily_usage_sd, c.daily_usage_sd) / nullif(coalesce(p.daily_usage_avg, c.daily_usage_avg), 0), 2) as cv,
  case when p.item_id is not null then '확정값' else '학습 기간 정제값' end as source
from calc c left join core.usage_profile p on p.item_id = c.item_id;

create or replace view analytics.v_data_coverage as
with bounds as (select min(use_date) as data_start, max(use_date) as data_end, count(*) as total_rows from raw.usage_history),
setting as (select * from core.forecast_setting where active order by setting_id limit 1),
train as (select count(*) as row_count from core.v_train_demand),
test as (select count(*) as row_count from core.v_test_actual)
select b.data_start, b.data_end, s.train_start, s.train_end, s.test_start, s.test_end,
  coalesce(t.row_count, 0) as train_row_count, coalesce(x.row_count, 0) as test_row_count,
  (s.train_start is not null and b.data_start <= s.train_start and b.data_end >= s.train_end) as train_window_ok,
  (s.test_start is not null and b.data_start <= s.test_start and b.data_end >= s.test_end) as test_window_ok,
  b.total_rows
from bounds b left join setting s on true cross join train t cross join test x;

create or replace view analytics.v_forecast_setting_summary as
select c.*, (select jsonb_agg(to_jsonb(p) order by p.config_key) from core.policy_config p) as policy_values,
  (select count(*) from core.item_policy) as item_policy_count,
  (select count(*) from core.outlier_rule where enabled) as enabled_outlier_rule_count
from analytics.v_data_coverage c;

