-- 기존 raw 테이블은 삭제하거나 재생성하지 않습니다.

do $$
declare table_name text;
begin
  foreach table_name in array array['shipment_log','supplier_master','item_master','inventory','usage_history','forecast','goods_receipt','purchase_order','dim_item','dim_model','fact_shipment','fact_mc_plan_actual','bridge_bom','bridge_scc_config','bridge_mc_cap','bridge_cap_option','bridge_option_model','bridge_xcn'] loop
    if to_regclass(format('raw.%I', table_name)) is not null then
      execute format('alter table raw.%I add column if not exists batch_id uuid', table_name);
      execute format('alter table raw.%I add column if not exists source_type text', table_name);
      execute format('alter table raw.%I add column if not exists loaded_at timestamptz default now()', table_name);
      execute format('alter table raw.%I add column if not exists source_record_id text', table_name);
    end if;
  end loop;
end $$;

create table if not exists raw.business_event (
  event_id text primary key,
  event_type text not null,
  event_date date,
  item_id text,
  model_base text,
  quantity numeric,
  attributes jsonb,
  batch_id uuid,
  source_type text,
  loaded_at timestamptz not null default now(),
  source_record_id text
);
create table if not exists raw.sales_order (
  sales_order_id text primary key,
  order_date date,
  customer_id text,
  item_id text,
  model_base text,
  quantity numeric,
  status text,
  batch_id uuid,
  source_type text,
  loaded_at timestamptz not null default now(),
  source_record_id text
);
create table if not exists raw.item_substitute (
  item_substitute_id bigint generated by default as identity primary key,
  item_id text not null,
  substitute_item_id text not null,
  priority integer,
  active boolean not null default true,
  batch_id uuid,
  source_type text,
  loaded_at timestamptz not null default now(),
  source_record_id text,
  unique (item_id, substitute_item_id)
